const fs = require('fs');
const path = require('path');

function walkDir(dir, callback) {
  fs.readdirSync(dir).forEach(f => {
    let dirPath = path.join(dir, f);
    let isDirectory = fs.statSync(dirPath).isDirectory();
    isDirectory ? walkDir(dirPath, callback) : callback(dirPath);
  });
}

walkDir('c:\\Desktop\\sujatafinejewels\\frontend\\src\\app\\admin', (filePath) => {
  if (filePath.endsWith('.tsx') || filePath.endsWith('.ts')) {
    let content = fs.readFileSync(filePath, 'utf8');
    // We want to replace localStorage.getItem("token") or localStorage.getItem('token') or localStorage.getItem(`token`)
    let newContent = content.replace(/localStorage\.getItem\(['"`]token['"`]\)/g, 'localStorage.getItem("adminToken")');
    if (content !== newContent) {
      fs.writeFileSync(filePath, newContent, 'utf8');
      console.log('Updated', filePath);
    }
  }
});
